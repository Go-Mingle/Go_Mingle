const byName = new Map(AMENITY_ICON_LIBRARY.map((icon) => [icon.name, icon]))

export const findLibraryIcon = (name: string | null | undefined): LibraryIcon | undefined =>
  name ? byName.get(name) : undefined

/** Library icons whose label, name or keywords match the query, in an optional category. */
export function searchLibraryIcons(
  query: string,
  category: IconCategory | 'all' = 'all',
): LibraryIcon[] {
  const q = query.trim().toLowerCase()
  return AMENITY_ICON_LIBRARY.filter(
    (icon) =>
      (category === 'all' || icon.category === category) &&
      (!q || `${icon.label} ${icon.name} ${icon.keywords ?? ''}`.toLowerCase().includes(q)),
  )
}
