/**
 * Regenerates contracts/admin.mjs and contracts/partner.mjs.
 *
 * Each portal's API contract (routes, request validation, response envelopes,
 * error codes) is defined in its typed handler modules under src/mocks/handlers,
 * which the portals' own test suites (~6,300 tests) exercise. Bundling them here
 * means the backend serves exactly the contract the frontends were built and
 * tested against. Seed data (Karachi restaurants, Minglers, PKR amounts) comes
 * from the same modules.
 *
 * Usage: node scripts/build-contracts.mjs <admin-web dir> <partner-web dir>
 *   (defaults: ../Admin and ../Partner)
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { stateAccessorPlugin } from './state-plugin.mjs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const [adminDir = path.resolve(root, '../Admin'), partnerDir = path.resolve(root, '../Partner')] =
  process.argv.slice(2)

const common = {
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  external: ['msw'],
  logLevel: 'warning',
  legalComments: 'none',
  loader: { '.png': 'dataurl', '.svg': 'dataurl', '.jpg': 'dataurl', '.jpeg': 'dataurl', '.webp': 'dataurl' },
  define: {
    'import.meta.env': JSON.stringify({ DEV: false, PROD: true, MODE: 'production' }),
  },
  banner: { js: '// Generated by scripts/build-contracts.mjs — do not edit by hand.' },
}

// Besides the route handlers, each entry exposes the data stores the API
// keeps in step across portals (restaurants, applications, notifications).
const ENTRIES = {
  admin: (dir) => `
export { handlers } from '${dir}/src/mocks/handlers/index'
export { mockRestaurants, mockApplications, mockCategories } from '${dir}/src/mocks/data/index'
export { mockAmenities } from '${dir}/src/mocks/data/amenities'
export { pushMockNotification } from '${dir}/src/mocks/handlers/notifications'
export { setMockCurrentUserId } from '${dir}/src/mocks/handlers/users'
export { stateModules } from 'gm-state-registry'
`,
  partner: (dir) => `
export { handlers } from '${dir}/src/mocks/handlers/index'
export * as profile from '${dir}/src/mocks/data/partnerRestaurantProfile'
export * as session from '${dir}/src/mocks/data/partnerSession'
export * as notifications from '${dir}/src/mocks/data/partnerNotifications'
export * as media from '${dir}/src/mocks/data/partnerMedia'
export * as tables from '${dir}/src/mocks/data/partnerTables'
export * as interestTables from '${dir}/src/mocks/data/partnerInterestTables'
export * as reviews from '${dir}/src/mocks/data/partnerReviews'
export * as finances from '${dir}/src/mocks/data/partnerFinances'
export * as webhooks from '${dir}/src/mocks/data/webhooks'
export * as menu from '${dir}/src/mocks/data/partnerMenu'
export * as users from '${dir}/src/mocks/data/partnerUsers'
export * as cdn from '${dir}/src/mocks/data/mockCdn'
export * as account from '${dir}/src/mocks/data/partnerAccount'
export { stateModules } from 'gm-state-registry'
`,
}

const tmpDir = path.join(root, '.build')
mkdirSync(tmpDir, { recursive: true })

for (const [name, dir] of [['admin', adminDir], ['partner', partnerDir]]) {
  const entry = path.join(tmpDir, `${name}-entry.ts`)
  writeFileSync(entry, ENTRIES[name](path.resolve(dir).split(path.sep).join('/')))
  await build({
    ...common,
    entryPoints: [entry],
    outfile: path.join(root, 'contracts', `${name}.mjs`),
    tsconfig: path.join(dir, 'tsconfig.app.json'),
    plugins: [stateAccessorPlugin(path.resolve(dir))],
  })
  // The contracts point uploads and media at placeholder hosts that only a
  // browser service worker could answer. Re-home them on this API server.
  const out = path.join(root, 'contracts', `${name}.mjs`)
  let code = readFileSync(out, 'utf8')
  for (const [from, to] of [
    ['"https://cdn.mock.local"', '(globalThis.GM_PUBLIC_URL + "/mock-cdn")'],
    ['"https://stream.mock.local"', '(globalThis.GM_PUBLIC_URL + "/mock-stream")'],
    ['"https://upload.mock.local"', '(globalThis.GM_PUBLIC_URL + "/mock-upload")'],
    ['"https://menu-upload.mock.local"', '(globalThis.GM_PUBLIC_URL + "/mock-menu-upload")'],
    ['"https://cdn.mock.local/', 'globalThis.GM_PUBLIC_URL + "/mock-cdn/'],
    ['https://mock-bucket.local/${', '${globalThis.GM_PUBLIC_URL}/mock-bucket/${'],
    ['/^https:\\/\\/mock-bucket\\.local\\//', '/\\/mock-bucket\\//'],
  ]) {
    code = code.split(from).join(to)
  }
  // Drop esbuild's per-module source-path comments (local machine paths).
  code = code.replace(/^\/\/ [^\n]*\.(?:ts|tsx|js|mjs|cjs|json)\n/gm, '')
  code = code.replace(/"[^"\n]*?node_modules\//g, '"node_modules/')
  writeFileSync(out, code)
  console.log(`contracts/${name}.mjs  <-  ${path.relative(root, dir)}`)
}
